def load_kangxi_strokes() -> dict:
    with open(KX_STROKES, "r", encoding="utf-8") as f:
        return json.load(f)


def load_kx_data() -> dict:
    with open(KX_DATA, "r", encoding="utf-8") as f:
        return json.load(f)


def load_level1() -> list[str]:
    with open(LEVEL1, "r", encoding="utf-8") as f:
        return [c.strip() for c in f if c.strip()]


def gen_pinyin(char: str) -> tuple[str, int]:
    """生成拼音（无声调）和声调数字"""
    try:
        normal = pinyin(char, style=Style.NORMAL)
        tone3 = pinyin(char, style=Style.TONE3)
        py = normal[0][0] if normal else ""
        t = 0
        if tone3 and tone3[0]:
            m = re.search(r"(\d)$", tone3[0][0])
            if m:
                t = int(m.group(1))
        return py, t
    except Exception:
        return "", 0


def get_wuxing(char: str, radical: str) -> str:
    """判定五行：手动覆盖 > 部首映射 > 默认"""
    if char in WUXING_OVERRIDE:
        return WUXING_OVERRIDE[char]
    if radical and radical in WUXING_RADICAL:
        return WUXING_RADICAL[radical]
    return DEFAULT_WUXING


def main():
    strokes = load_kangxi_strokes()
    kx = load_kx_data()
    radical_map = kx["radical"]
    level1 = load_level1()

    print(f"康熙笔画 {len(strokes)} 字，部首 {len(radical_map)} 字，常用字表 {len(level1)} 字")

    # 加载现有字库，保留已有数据
    with open(CHARS_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)
    existing = {c["char"] for c in data["chars"]}

    added = 0
    no_stroke = 0
    for char in level1:
        if char in existing:
            continue
        if char not in strokes:
            no_stroke += 1
            continue

        py, tone = gen_pinyin(char)
        radical = radical_map.get(char, "")
        wuxing = get_wuxing(char, radical)
        luck = "凶" if char in BAD_CHARS else "吉"

        entry = {
            "char": char,
            "pinyin": py,
            "tone": tone,
            "radical": radical,
            "kangxi_strokes": strokes[char],
            "simplified_strokes": strokes[char],  # 占位，业务未使用
            "wuxing": wuxing,
            "luck": luck,
            "gender": "中",
            "meaning": "",
            "shuowen": "",
            "detail": "",
        }
        data["chars"].append(entry)
        existing.add(char)
        added += 1

    data["total"] = len(data["chars"])
    data["version"] = "3.0"

    # 统计五行分布
    wx_count = {}
    for c in data["chars"]:
        wx = c["wuxing"]
        wx_count[wx] = wx_count.get(wx, 0) + 1
    data["wuxing_distribution"] = wx_count

    with open(CHARS_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"新增 {added} 字，无康熙笔画跳过 {no_stroke} 字，字库总数 {data['total']}，版本 {data['version']}")
    print(f"五行分布: {wx_count}")


if __name__ == "__main__":
    main()
