def build_taste(out: Path) -> None:
    """产出 pair_taste.json：TOP→5、GOOD→4、OK→3，其余一律 1（默认屏蔽）。

    白名单是**唯一出口**：任何新增字对若未在此定级，都按 1 分处理（不出），
    以保证「语料扩充」不会把旧毛病带回来。漏定的代价是名字变少（可见、可测），
    而不是默默变土（不可见）——这是刻意选择的安全侧。
    """
    rows = flatten(load_pairs())
    words = sorted({w for w, _ in rows})
    scores: dict[str, int] = {}
    for w in words:
        if w in TOP:
            scores[w] = 5
        elif w in GOOD:
            scores[w] = 4
        elif w in OK:
            scores[w] = 3
        elif w in EXTRA:
            scores[w] = EXTRA[w]
        elif w in EXTRA2:
            scores[w] = EXTRA2[w]
        elif w in EXTRA3:
            scores[w] = EXTRA3[w]
        elif w in EXTRA4:
            scores[w] = EXTRA4[w]
        elif w in EXTRA5:
            scores[w] = EXTRA5[w]
        elif w in PROMOTE_CI:
            scores[w] = PROMOTE_CI[w]
        else:
            scores[w] = 1
    # 倒序：显式定级覆盖（可能与某个正序同名，冲突要报出来）
    for w, s in {**REV, **EXTRA_REV, **EXTRA2_REV, **EXTRA3_REV, **EXTRA4_REV}.items():
        if w in scores and scores[w] != s:
            print(f"[taste] 警告：{w} 正序 {scores[w]} 分与倒序 {s} 分冲突，以倒序为准")
        scores[w] = s

    out.write_text(
        json.dumps(
            {"_meta": {"判据": "愿不愿意写在出生证明上",
                       "levels": "5=优先 4=可用 3=兜底 1=屏蔽",
                       "policy": "白名单外默认 1（屏蔽）；未定级的新字对不出",
                       "single": "单字名（name_length=1）单独定级，判据是「一个字能否独自立住」"},
             "scores": scores,
             "single": single_scores()},
            ensure_ascii=False, indent=1,
        ),
        encoding="utf-8",
    )
    single = single_scores()
    sdist = {s: sum(1 for v in single.values() if v == s) for s in (5, 4, 3, 1)}
    print(f"[taste] 单字 {len(single)} 个 → {sdist}")
    # 同一字出现在多档时 single_scores() 按 3→4→5 覆盖，最终 5 分胜出，
    # 属于「写重了也不报错」的静默错误，故单独检出。
    single_overlap = (
        (SINGLE_5 & SINGLE_4) | (SINGLE_5 & SINGLE_3) | (SINGLE_4 & SINGLE_3)
        | (SINGLE_BAN & (SINGLE_5 | SINGLE_4 | SINGLE_3))
    )
    if single_overlap:
        print(f"[taste] 警告：单字重复定级 {sorted(single_overlap)}")
    dist = {s: sum(1 for v in scores.values() if v == s) for s in (5, 4, 3, 1)}
    print(f"[taste] {len(words)} 个字对 → {dist}")
    overlap = (TOP & GOOD) | (TOP & OK) | (GOOD & OK)
    if overlap:
        print(f"[taste] 警告：同一字对出现在多个档位 {sorted(overlap)}")
    contradict = BAN_EXTRA & (TOP | GOOD | OK)
    if contradict:
        print(f"[taste] 警告：既在屏蔽样例又在白名单 {sorted(contradict)}")
    stray = (TOP | GOOD | OK | set(EXTRA) | set(EXTRA2) | set(EXTRA3) | set(EXTRA4) | set(EXTRA5) | set(PROMOTE_CI)) - set(words)
    if stray:
        print(f"[taste] 警告：定级了语料里不存在的字对 {sorted(stray)}")
    for s, names in ((5, TOP), (4, GOOD), (3, OK)):
        print(f"  {s} 分（{len(names)}）：", " ".join(sorted(names)))


