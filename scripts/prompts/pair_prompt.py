"""
「宜作名字对」标注提示词

任务：给定一条出处（诗/词/古文摘句），挑出 2~4 组**可以直接作为双字名**的字对，
产出 data/poetry/name_pairs.json（entry_id -> [[c1, c2], ...]）。

为什么需要这一步（背景）：
诗词标注产出的是「一袋好字」（recommend_chars 2~5 个），组合层再用
C(n,2) 全交叉造配对。实测 3378 个配对里 65.5% 的两字在原文中分处不同分句
（「萸橘」式机械拼接）；而「圣人」「教多」「用财」这类虽在原句同句，
却不成意象、不宜作名。前者可由 pair_cohesion 判定，后者只能靠语义判断 —— 即本任务。

与 recommend_chars 的关系：
- recommend_chars 不动（仍是单字池，供随机组合与单字名使用）。
- 本任务产出的 recommend_pairs 是**增量的成对候选**，组合层优先使用。
- 可随时回退（不删除已有字段）。

硬性约束（违反即判无效；服务端另有独立校验，不合规的字对会被丢弃）：
1. 字对中的每个字【必须】出现在给定摘句里，一个字都不能自造。
2. 两字必须【在同一分句内相邻】（如「婵娟」「清扬」），或【同分句内可解释为一对】
   （如「桃之夭夭，灼灼其华」取「灼华」）。严禁跨分句凑对。
3. 必须**像一个名字**，而不是「原句里的一个词组」。
4. 输出格式：pairs 是**字符串数组**，每个字符串**恰好两个汉字**（就是一个双字名）。
5. 只输出合法 JSON（配合 response_format=json_object）。
"""

from __future__ import annotations

SYSTEM_PROMPT = (
    "你是一位精通中国古典诗词与用典起名的专家。"
    "你的任务是从一句诗文中挑出【可以直接作为双字名】的两字组合。"
    "判断标准不是「这两个字是不是原句里的词」，而是「这对字本身像不像一个名字」："
    "意象完整、雅正、适合人名，拿出去不会让人觉得奇怪或老气。"
    "宁可返回空数组，也不要凑数。"
    "你只输出一个合法 JSON 对象，不输出任何解释、前后缀或 markdown 代码块。"
)

OUTPUT_TEMPLATE = """{
  "pairs": ["婵娟", "清扬"],
  "note": "「婵娟」原句成词，月色美好；「清扬」眉目清朗、神采飞扬"
}"""

HARD_RULES = """硬性规则（必须全部满足）：
1. 【只准用原句中的字】每个两字组合中的字都必须出现在给定摘句里。严禁自造或替换
   （例：「老骥伏枥，志在千里」里**没有**「远」字，因此不能给「志远」）。
2. 【必须同分句】两字须满足其一：
   ① 在原文中**相邻**（如「婵娟」「清扬」「素秋」）；或
   ② 在**同一个分句内**可解释为一对（如「桃之夭夭，灼灼其华」取「灼华」）。
   严禁把分处两个分句的字凑成一对（「白酒红萸，黄花绿橘」不得取「萸橘」）。
3. 【必须像名字，不是词组】这是最重要的一条。以下四类一律不要选：
   - 称谓 / 论断 / 评价：圣人、君子、大知、廉正、固朝、**壮心**、**中立**
   - 功能 / 抽象 / 空泛：教多、用财、在志、里志、有土、**用明**、**用恩**
   - 器物 / 物产 / 谶语感：红萸、黄橘、年寿、延寿、**石上**、**社方**
   - **成语 / 固定短语 / 动作连用 / 关系称谓**：切磋、琢磨、辗转、徜徉、**知己**
   正例（可以选）：修远、望舒、素秋、琼玉、清扬、玉瓒、灼华、眠云、听雪。
4. 【格式】pairs 是**字符串数组**，每个元素是**恰好两个汉字**的字符串。
   严禁嵌套数组。错误：[["婵","娟"]]、[["修远","漫漫"]]；正确：["婵娟", "修远"]。
5. 【顺序按原文语序】成词的字按词序（「婵娟」不得写成「娟婵」）。
6. pairs 共 2~4 个，互不重复。
   若该句确实没有适合做名字的两字组合（哀伤句、纯议论句、口号句），返回空数组 []。
7. 只输出一个 JSON，字段齐全，不要输出任何解释。"""


def build_user_prompt(
    entry: dict, banned: set[str] | None = None, existing: list[str] | None = None
) -> str:
    """构建用户提示词。

    Args:
        entry: {source, title, author, dynasty, text, citation, recommend_chars}
        banned: 已被复核判定不适合做人名的组合（补标注时传入，避免重复踩坑）
        existing: 该出处**已收录**的字对（增补模式传入，只要求**追加**新字对）
    """
    lines = [
        f"出处：{entry.get('citation') or entry.get('title') or ''}",
        f"原文：{entry.get('text') or ''}",
    ]
    chars = entry.get("recommend_chars") or []
    if chars:
        lines.append(f"参考（系统已标注的推荐字，仅作提示）：{'、'.join(chars)}")
    lines.append("")
    if banned:
        # 只列出与本句有交集的黑名单项，避免提示词过长、也避免模型被无关词干扰
        text = entry.get("text") or ""
        related = sorted(w for w in banned if w[0] in text or w[1] in text)
        if related:
            lines.append(
                "以下组合已被判定**不适合做人名**，本句若涉及请一律不要选："
                + "、".join(related[:40])
            )
            lines.append("")
    if existing:
        lines.append(
            "以下组合**已收录**，不要再重复；请从原句的其他位置**另行补充**新字对："
            + "、".join(existing)
        )
        lines.append("最多补充 4 组；若确实没有更多合适的，返回空数组 []。")
    else:
        lines.append("请挑出可以直接作为双字名的字对，严格按下面的格式输出：")
    lines.append(OUTPUT_TEMPLATE)
    return "\n".join(lines)
