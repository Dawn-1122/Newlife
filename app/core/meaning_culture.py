def culture_chars_for(meanings) -> set:
    """把选中的期许展开成一个字集合（供引擎做命中判定）。"""
    out: set = set()
    for code in meanings or []:
        out.update(MEANING_CULTURE_CHARS.get(code, ()))
    return out


def culture_hits(chars, meanings) -> list:
    """
    名字用字里命中了哪些「期许文化记号」。

    Args:
        chars: 名字的用字列表（如 ["松", "茂"]）
        meanings: 选中的期许 code 列表；为空时返回空表

    Returns:
        [{"char": "松", "codes": ["health"], "note": "《论语》…"}]
        一个字可能同时对应多个期许（松 → 健康 + 坚韧），codes 全部列出，
        前端只展示第一句 note。
    """
    if not meanings:
        return []

    hits = []
    for ch in chars or []:
        codes = [c for c in meanings if ch in MEANING_CULTURE_CHARS.get(c, ())]
        if not codes:
            continue
        hits.append({
            "char": ch,
            "codes": codes,
            "note": CHAR_VIRTUE_NOTES.get(ch, ""),
        })
    return hits
